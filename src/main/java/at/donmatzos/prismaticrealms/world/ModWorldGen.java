package at.donmatzos.prismaticrealms.world;

import net.fabricmc.fabric.api.biome.v1.BiomeModifications;
import net.fabricmc.fabric.api.biome.v1.BiomeSelectors;

import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.tags.TagKey;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.levelgen.GenerationStep;
import net.minecraft.world.level.levelgen.feature.Feature;
import net.minecraft.world.level.levelgen.placement.PlacedFeature;

import at.donmatzos.prismaticrealms.PrismaticRealms;
import at.donmatzos.prismaticrealms.block.ModBlocks;

/**
 * Crystal ore generation: every ore is rare across the whole overworld, plus a much stronger boosted placement
 * in its family's biomes (biome tag {@code has_crystal_ore/<family>}). Features and placements are generated by datagen.
 */
public final class ModWorldGen {
	private ModWorldGen() {
	}

	public static ResourceKey<Feature> oreFeature(String family, boolean boosted) {
		return ResourceKey.create(Registries.FEATURE, PrismaticRealms.id(orePath(family, boosted)));
	}

	public static ResourceKey<PlacedFeature> orePlacement(String family, boolean boosted) {
		return ResourceKey.create(Registries.PLACED_FEATURE, PrismaticRealms.id(orePath(family, boosted)));
	}

	public static TagKey<Biome> boostedBiomes(String family) {
		return TagKey.create(Registries.BIOME, PrismaticRealms.id("has_crystal_ore/" + family));
	}

	private static String orePath(String family, boolean boosted) {
		return "ore_" + family + (boosted ? "_boosted" : "");
	}

	public static void initialize() {
		for (ModBlocks.CrystalOre ore : ModBlocks.CRYSTAL_ORES) {
			BiomeModifications.addFeature(BiomeSelectors.foundInOverworld(), GenerationStep.Decoration.UNDERGROUND_ORES, orePlacement(ore.family(), false));
			BiomeModifications.addFeature(BiomeSelectors.tag(boostedBiomes(ore.family())), GenerationStep.Decoration.UNDERGROUND_ORES, orePlacement(ore.family(), true));
		}
	}
}
